import {writeFile} from 'node:fs/promises';
import family from '../src/family.mjs';
import {PUBLIC_WRITE_TOKEN} from '../src/worker.mjs';

// This public, static snapshot lets the tree start even when the dynamic Worker is limited.
// Live birthdays, uploads and edits still come from /family-data.js and the APIs when available.
const script='// Generated by scripts/build-family-fallback.mjs; do not edit by hand.\n'+
  'window.FAMILY_DATA ||= '+JSON.stringify(family)+';\n'+
  'window.LOCAL_FAMILY_SERVER ??= true;\n'+
  'window.FAMILY_API_TOKEN ??= '+JSON.stringify(PUBLIC_WRITE_TOKEN)+';\n'+
  'window.FAMILY_CLOUD ??= true;\n'+
  'window.FAMILY_DATA_AVAILABLE ??= false;\n';
await writeFile(new URL('../public/assets/family-fallback.js',import.meta.url),script);
